def select_original(label, options, key=None):
    values = [value for value, translation in options]

    def formatter(value):
        for original, translation in options:
            if original == value:
                return t[translation]
        return str(value)

    return st.selectbox(
        label,
        values,
        format_func=formatter,
        key=key
    )


def get_risk(probability):
    if probability < 0.15:
        return t["low"], "success"
    if probability < 0.40:
        return t["moderate"], "warning"
    return t["high"], "error"


